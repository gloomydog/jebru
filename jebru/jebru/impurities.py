def short(name: str) -> str:
    return SHORT.get(name, name)


@dataclass
class SignalHit:
    group: str
    expected: float
    found: float | None


@dataclass
class ImpurityMatch:
    name: str
    status: str                      # "confirmed" (all signals) | "possible"
    hits: list = field(default_factory=list)

    @property
    def label(self):
        return short(self.name) + ("" if self.status == "confirmed" else "?")


