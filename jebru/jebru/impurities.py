def table_for(solvent: str, nucleus: str):
    if solvent not in COLS:
        return {}
    k = COLS.index(solvent)
    src = H1 if nucleus == "1H" else C13 if nucleus == "13C" else {}
    out = {}
    for name, sigs in src.items():
        if _SELF.get(solvent) == name:
            continue
        rows = []
        for s in sigs:
            shifts = s[-1]
            if shifts[k] is not None:
                rows.append((s[0], shifts[k]) if nucleus == "13C" else (s[0], shifts[k], s[1], s[2]))
        if rows and len(rows) == len(sigs):
            out[name] = rows
    return out


_MULT_OK = {
    "s": {"s", "br s"}, "br s": {"s", "br s", "m"}, "d": {"d"}, "t": {"t"}, "q": {"q"},
    "sept": {"hept", "h", "m"}, "m": {"m", "br s"},
    "dt": {"dt", "td", "dq", "m"}, "dm": {"d", "dd", "dt", "ddd", "m"},
}


def find_impurities(cands, solvent: str, nucleus: str, tol: float | None = None) -> list[ImpurityMatch]:
    """cands: observed signals as (ppm, multiplicity or None, amount or None).

    * every signal of a multi-signal compound must be present with a matching
      multiplicity (1H) and, for 1H, integrals in the expected ratio (±60 %)
      -> 'confirmed';
    * single-signal compounds with matching position/multiplicity -> 'possible';
    * partial matches are ignored (too many coincidences with real signals)."""
    if tol is None:
        tol = 0.025 if nucleus == "1H" else 0.3
    cands = [c if isinstance(c, (tuple, list)) else (c, None, None) for c in cands]
    matches = []
    for name, rows in table_for(solvent, nucleus).items():
        hits, amounts = [], []
        for r in rows:
            exp = r[1]
            exp_mult = r[2] if nucleus == "1H" else None
            best = None
            for ppm, mult, amt in cands:
                if abs(ppm - exp) > tol:
                    continue
                if exp_mult and mult is not None and mult not in _MULT_OK.get(exp_mult, {mult}):
                    continue
                if best is None or abs(ppm - exp) < abs(best[0] - exp):
                    best = (ppm, mult, amt)
            hits.append(SignalHit(r[0], exp, None if best is None else float(best[0])))
            if best is not None and best[2] is not None and nucleus == "1H" and r[3]:
                amounts.append(best[2] / r[3])
        if not all(h.found is not None for h in hits):
            continue
        if len(hits) == 1:
            matches.append(ImpurityMatch(name, "possible", hits))
            continue
        if amounts and len(amounts) == len(hits) and max(amounts) > 1.6 * min(amounts):
            continue
        matches.append(ImpurityMatch(name, "confirmed", hits))
    # a position explained by a confirmed compound is not also a 'possible' one
    used = {h.found for m in matches if m.status == "confirmed" for h in m.hits}
    matches = [m for m in matches if m.status == "confirmed" or m.hits[0].found not in used]
    matches.sort(key=lambda m: (m.status != "confirmed", m.name))
    return matches
